// labeling.ts — shared, dependency-free helpers for the "Label my print" flow.
// Kept free of Next/Vercel imports so it is trivially unit-testable.

// The one written definition of "failure" every student sees before labeling.
// Keep this wording in sync with the lab notebook / analysis plan: inconsistent
// thresholds between raters cannot be fixed by any amount of modeling.
export const FAILURE_DEFINITION =
  "A print FAILED if it did not complete, or it completed but was unusable for its intended purpose.";

export type Outcome = "succeeded" | "failed";

export const OUTCOMES: readonly Outcome[] = ["succeeded", "failed"] as const;

export function isOutcome(value: unknown): value is Outcome {
  return value === "succeeded" || value === "failed";
}

// Canonical student identifier. MUST mirror station/matching.py normalize_netid:
// lower-case, anything outside [a-z0-9._-] collapsed to "_", trimmed, max 64.
// Returns null when nothing usable is left.
export function normalizeNetId(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const cleaned = raw
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 64);
  return cleaned || null;
}

// Print job ids are UUIDs generated by the station (str(uuid.uuid4())).
const JOB_ID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isJobId(value: unknown): value is string {
  return typeof value === "string" && JOB_ID_RE.test(value);
}

// One row returned by the station's /api/my-prints.
export interface MyPrint {
  job_id: string;
  filename: string | null;
  subtask_name: string | null;
  printer_name: string;
  printer_serial: string;
  start_time: string | null;
  end_time: string | null;
  user_label: number | null; // 0 = succeeded, 1 = failed, null = not labeled yet
  label_source: string | null;
  match_confidence: string;
}

export interface MyPrintsResponse {
  netid: string;
  window_days: number;
  prints: MyPrint[];
}

export function outcomeFromLabel(label: number | null): Outcome | null {
  if (label === 0) return "succeeded";
  if (label === 1) return "failed";
  return null;
}

